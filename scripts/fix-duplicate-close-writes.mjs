/**
 * scripts/fix-duplicate-close-writes.mjs — remove rows written twice by two
 * different channels, and status history rows that record nothing.
 *
 * WHY THIS EXISTS
 * ───────────────
 * Tickets are closed two ways in practice: through the app
 * (POST /api/automation/close, which is idempotent — a second call on an
 * already-closed ticket returns `alreadyClosed` and writes nothing), and by an
 * external agent writing straight into the tables. When both ran on the same
 * ticket, within the same second, the ticket ended up with the reply and the
 * technician note stored twice, and with a `status` history row whose old and
 * new value are both "סגור" — a change that never happened. REQ-732 and
 * HDTC-671 are the two tickets where that was visible to a reader.
 *
 * TELLING THE TWO WRITERS APART
 * ─────────────────────────────
 * A row Prisma creates gets a cuid v1 id, and the 8 characters after the
 * leading "c" are base36 Date.now() AT THE MOMENT OF THE INSERT. So for every
 * row the app wrote, the id decodes to the row's own createdAt. The rows
 * written directly carry ids that were made up: they decode to dates months
 * away from when the row was stored, and three rows inserted in one
 * transaction carry three different "fingerprint" sections, which a real cuid
 * library cannot produce. `writtenByTheApp()` below is that check, and it is
 * how the script decides which twin to keep — the genuine one, the one the
 * closure mail and the rest of the audit trail belong to.
 *
 * WHAT IT DELETES
 * ───────────────
 *   1. TicketHistory rows with field "status" where oldValue === newValue.
 *      GUARDED: a closure row is never removed if it is the only
 *      `newValue: "סגור"` row on its ticket. Ticket has no closedAt column —
 *      the reports and the export derive the closing date from that row
 *      (see scripts/audit-close-dates.mjs), so removing the last one would
 *      erase the ticket's closing date everywhere, permanently.
 *   2. TicketMessage rows that repeat another message on the same ticket:
 *      identical content, identical author, stored within WINDOW_MS.
 *   3. TicketNote rows, by the same rule.
 *   4. TicketHistory rows that repeat another row on the same ticket: same
 *      field, same old and new value, same actor, within WINDOW_MS. One write
 *      recorded twice reads as the change having happened twice. A group
 *      always keeps one row, so a closure recorded twice stays recorded.
 *
 * Only one of each pair goes. Nothing is deleted where there is a single row.
 *
 * USAGE (on the server, where DATABASE_URL is set):
 *
 *   cd /home/ubuntu/helpdesk
 *   set -a; . ./.env; set +a
 *   node scripts/fix-duplicate-close-writes.mjs           # dry run, changes nothing
 *   node scripts/fix-duplicate-close-writes.mjs --apply   # delete, in one transaction
 *
 * The dry run is the default on purpose: read the plan, then re-run with
 * --apply. There is no undo.
 */

import { PrismaClient } from "@prisma/client"

if (!process.env.DATABASE_URL) {
  console.error("")
  console.error("DATABASE_URL is not set, so there is no database to repair.")
  console.error("")
  console.error("This script touches the live database, and the credentials live in")
  console.error(".env on the server (gitignored, so never in a local checkout).")
  console.error("")
  console.error("  cd /home/ubuntu/helpdesk")
  console.error("  set -a; . ./.env; set +a")
  console.error("  node scripts/fix-duplicate-close-writes.mjs")
  console.error("")
  process.exit(1)
}

const APPLY     = process.argv.includes("--apply")
const WINDOW_MS = 10_000
const CLOSED    = "סגור"

const prisma = new PrismaClient()

/**
 * True when the id was generated by the process that stored the row — a cuid
 * v1 whose timestamp section is the row's own creation time. A tolerance of a
 * minute is far wider than any clock drift between the id and the INSERT, and
 * far narrower than the months the fabricated ids are off by.
 */
function writtenByTheApp(id, createdAt) {
  if (typeof id !== "string" || id.length !== 25 || id[0] !== "c") return false
  const stamp = Number.parseInt(id.slice(1, 9), 36)
  if (!Number.isFinite(stamp)) return false
  return Math.abs(stamp - createdAt.getTime()) <= 60_000
}

/** Of two rows holding the same text, the one worth keeping. */
function pickSurvivor(rows) {
  const genuine = rows.filter(r => writtenByTheApp(r.id, r.createdAt))
  const pool = genuine.length > 0 ? genuine : rows
  return pool.reduce((a, b) => (a.createdAt <= b.createdAt ? a : b))
}

const label = t => `${t.type === "request" ? "REQ" : "HDTC"}-${t.ticketNumber}`
const when  = d => d.toISOString().replace("T", " ").slice(0, 23)
const short = s => s.replace(/\s+/g, " ").trim().slice(0, 48)

/** Status history rows that record a change from a value to itself. */
async function findNoopStatusRows() {
  const rows = await prisma.ticketHistory.findMany({
    where: { field: "status" },
    select: { id: true, ticketId: true, oldValue: true, newValue: true, changedAt: true },
    orderBy: { changedAt: "asc" },
  })
  const noop = rows.filter(r => r.oldValue !== null && r.oldValue === r.newValue)

  const plan = []
  for (const row of noop) {
    // The closing date lives in the latest "→ סגור" row and nowhere else.
    // The row that has to survive is a REAL closure: counting another no-op
    // row here would let two no-ops vouch for each other and both go.
    const others = rows.filter(
      r => r.ticketId === row.ticketId && r.id !== row.id &&
           r.newValue === CLOSED && r.oldValue !== r.newValue,
    )
    if (row.newValue === CLOSED && others.length === 0) {
      plan.push({ ...row, keep: true, why: "the only closure row on this ticket — it carries the closing date" })
    } else {
      plan.push({ ...row, keep: false })
    }
  }
  return plan
}

/** What makes two rows the same write: everything the writer chose. */
const textKey    = r => `${r.ticketId}\u0000${r.authorEmail ?? ""}\u0000${r.content}`
const historyKey = r => `${r.ticketId}\u0000${r.actorEmail ?? ""}\u0000${r.field}\u0000${r.oldValue ?? ""}\u0000${r.newValue ?? ""}`

/** Rows repeating another row on the same ticket, within WINDOW_MS. */
function duplicateGroups(rows, key = textKey) {
  const byKey = new Map()
  for (const row of rows) {
    const k = key(row)
    if (!byKey.has(k)) byKey.set(k, [])
    byKey.get(k).push(row)
  }

  const groups = []
  for (const sameText of byKey.values()) {
    if (sameText.length < 2) continue
    sameText.sort((a, b) => a.createdAt - b.createdAt)
    // A run of rows each within WINDOW_MS of the previous one is one write
    // seen twice. Two identical messages days apart are two real messages.
    let run = [sameText[0]]
    for (const row of sameText.slice(1)) {
      if (row.createdAt - run[run.length - 1].createdAt <= WINDOW_MS) run.push(row)
      else { if (run.length > 1) groups.push(run); run = [row] }
    }
    if (run.length > 1) groups.push(run)
  }
  return groups
}

async function main() {
  const tickets = await prisma.ticket.findMany({ select: { id: true, ticketNumber: true, type: true } })
  const ticketById = new Map(tickets.map(t => [t.id, t]))

  const [messages, notes] = await Promise.all([
    prisma.ticketMessage.findMany({ select: { id: true, ticketId: true, content: true, authorEmail: true, createdAt: true } }),
    prisma.ticketNote.findMany({ select: { id: true, ticketId: true, content: true, authorEmail: true, createdAt: true } }),
  ])

  // changedAt is history's createdAt; giving it that name lets the duplicate
  // grouping and the survivor rule below be the same code for every table.
  const historyRows = (await prisma.ticketHistory.findMany({
    select: { id: true, ticketId: true, field: true, oldValue: true, newValue: true, actorEmail: true, changedAt: true },
  })).map(r => ({ ...r, createdAt: r.changedAt }))

  const msgGroups  = duplicateGroups(messages)
  const noteGroups = duplicateGroups(notes)
  const histGroups = duplicateGroups(historyRows, historyKey)
  const history    = await findNoopStatusRows()

  const doomed = { TicketMessage: [], TicketNote: [], TicketHistory: [] }

  console.log("")
  console.log(APPLY ? "APPLYING — rows below will be deleted." : "DRY RUN — nothing will be changed.")

  for (const [title, groups, table] of [
    ["Duplicate messages", msgGroups, "TicketMessage"],
    ["Duplicate notes",    noteGroups, "TicketNote"],
  ]) {
    console.log(`\n── ${title} ${"─".repeat(Math.max(0, 60 - title.length))}`)
    if (groups.length === 0) { console.log("   none"); continue }
    for (const group of groups) {
      const survivor = pickSurvivor(group)
      const t = ticketById.get(group[0].ticketId)
      console.log(`\n   ${t ? label(t) : group[0].ticketId}  "${short(group[0].content)}"`)
      for (const row of group) {
        const mark = row.id === survivor.id ? "keep  " : "DELETE"
        const src  = writtenByTheApp(row.id, row.createdAt) ? "app" : "direct write"
        console.log(`     ${mark} ${row.id}  ${when(row.createdAt)}  ${src}`)
        if (row.id !== survivor.id) doomed[table].push(row.id)
      }
    }
  }

  console.log(`\n── Duplicate history rows ${"─".repeat(36)}`)
  if (histGroups.length === 0) console.log("   none")
  for (const group of histGroups) {
    const survivor = pickSurvivor(group)
    const t = ticketById.get(group[0].ticketId)
    console.log(`\n   ${t ? label(t) : group[0].ticketId}  ${group[0].field}: ${group[0].oldValue ?? "—"} -> ${group[0].newValue ?? "—"}`)
    for (const row of group) {
      const mark = row.id === survivor.id ? "keep  " : "DELETE"
      const src  = writtenByTheApp(row.id, row.createdAt) ? "app" : "direct write"
      console.log(`     ${mark} ${row.id}  ${when(row.createdAt)}  ${src}`)
      if (row.id !== survivor.id) doomed.TicketHistory.push(row.id)
    }
  }

  console.log(`\n── Status history rows that record no change ${"─".repeat(17)}`)
  if (history.length === 0) console.log("   none")
  for (const row of history) {
    const t = ticketById.get(row.ticketId)
    const mark = row.keep ? "keep  " : "DELETE"
    console.log(`   ${mark} ${t ? label(t) : row.ticketId}  ${row.oldValue} -> ${row.newValue}  ${when(row.changedAt)}${row.keep ? `  (${row.why})` : ""}`)
    if (!row.keep) doomed.TicketHistory.push(row.id)
  }

  // A row can be caught by two rules at once — a repeat that also records no
  // change. It is still one row.
  for (const table of Object.keys(doomed)) doomed[table] = [...new Set(doomed[table])]

  const total = Object.values(doomed).reduce((n, ids) => n + ids.length, 0)
  console.log("")
  console.log(`── Total: ${total} row(s) — ${doomed.TicketMessage.length} message(s), ${doomed.TicketNote.length} note(s), ${doomed.TicketHistory.length} history row(s)`)

  if (!APPLY) {
    console.log("\nDry run. Re-run with --apply to delete them.\n")
    return
  }
  if (total === 0) { console.log("\nNothing to do.\n"); return }

  // One transaction: the whole repair, or none of it.
  await prisma.$transaction([
    prisma.ticketMessage.deleteMany({ where: { id: { in: doomed.TicketMessage } } }),
    prisma.ticketNote.deleteMany({ where: { id: { in: doomed.TicketNote } } }),
    prisma.ticketHistory.deleteMany({ where: { id: { in: doomed.TicketHistory } } }),
  ])
  console.log("\nDone.\n")
}

main()
  .catch(err => { console.error(err); process.exitCode = 1 })
  .finally(() => prisma.$disconnect())
